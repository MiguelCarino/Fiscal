// Carino Fiscal — offline cache.
//
// Offline is the premise, not an enhancement: a counter in a basement with no
// signal is exactly where this app has to work. So the whole site is
// precached on install, and every fetch is served cache-first.
//
// Cache-first is safe here because the app makes no network requests of its own
// once loaded — there is no live data to go stale. The only thing that changes
// is the app itself, and VERSION is a hash of the shipped bytes, so a new build
// gets a new cache without anybody having to remember to say so.
//
// The lists below are derived from the repo by tools/build_sw.py. Editing them
// by hand is how a file comes to be shipped but not cached, which is the one
// failure this app cannot afford; run the script instead. tools/validate.py
// runs the same code as a check and fails the build on a block that has
// drifted, because three rounds of asking people to remember produced three
// stale blocks.
//
// The lists are still not the last word: see declared() for the shipped files
// the app itself treats as authoritative about what exists, which the worker
// reads at install time and precaches regardless of what the script last saw.
// What that cannot repair is VERSION, because a stale one means sw.js's own
// bytes never change and no browser ever reinstalls it — which is why the gate
// matters. Nothing declared is ever counted as cached: readiness is measured
// against the cache itself, in offlineStatus().

// --- begin generated by tools/build_sw.py ---
